    private void loadTableData(){
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) deptTable.getModel();
        model.setRowCount(0);
        
        DepartmentFileHandle handle = new DepartmentFileHandle();
        String[][] allDepts = handle.getAllDepartments();
        
        for (int i = 0; i < allDepts.length; i++){
            if (allDepts[i][0] != null){
                model.addRow(allDepts[i]);
            }
        }
        
        deptTable.getColumnModel().getColumn(0).setPreferredWidth(100);  
        deptTable.getColumnModel().getColumn(1).setPreferredWidth(120); 
        deptTable.getColumnModel().getColumn(2).setPreferredWidth(300); 
    }
