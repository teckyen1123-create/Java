    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {                                       
        // TODO add your handling code here:
        String id = txtDeptID.getText();
        String name = txtDeptName.getText();
        String desc = txtDeptDesc.getText();
        
        if (id.isEmpty() || name.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "ID and Name cannot be empty.");
            return;
        }
        
        DepartmentFileHandle handle = new DepartmentFileHandle();
        if (handle.addDepartment(id, name, desc)){
            javax.swing.JOptionPane.showMessageDialog(this, "Added Successfully.");
            loadTableData();
        } else{
            javax.swing.JOptionPane.showMessageDialog(this, "Error Adding Department.");
        }
    }                                      

