    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {                                          
        // TODO add your handling code here:
        String id = txtDeptID.getText();
        String name = txtDeptName.getText();
        String desc = txtDeptDesc.getText();
        
        DepartmentFileHandle handle = new DepartmentFileHandle();
        if (handle.updateDepartment(id, name, desc)){
            javax.swing.JOptionPane.showMessageDialog(this, "Updated Successfully.");
            loadTableData();
        } else{
            javax.swing.JOptionPane.showMessageDialog(this, "Error Updating Department.");
        }
    }                                         

    private void btnClearActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        txtDeptID.setText("");
        txtDeptName.setText("");
        txtDeptDesc.setText("");
        txtDeptID.setEditable(true);
    }                                        

    private void deptTableMouseClicked(java.awt.event.MouseEvent evt) {                                       
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) deptTable.getModel();
        int selectedRow = deptTable.getSelectedRow();
        
        txtDeptID.setText(model.getValueAt(selectedRow, 0).toString());
        txtDeptName.setText(model.getValueAt(selectedRow, 1).toString());
        txtDeptDesc.setText(model.getValueAt(selectedRow, 2).toString());
        
        txtDeptID.setEditable(false);
    }                                      

